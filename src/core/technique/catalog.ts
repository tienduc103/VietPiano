/** Bài áp dụng vào bản nhạc → id bài Thư viện. */
const LIBRARY_LINKS: Record<string, string> = {
  'tech-l3-apply-happy-birthday': 'song-happy-birthday-beginner',
  'tech-l5-apply-ode-to-joy': 'song-ode-to-joy-2-hands',
};

function build(): FingerExercise[] {
  const out: FingerExercise[] = [];
  for (const d of DEFS) {
    const libId = LIBRARY_LINKS[d.id];
    if (libId) {
      const lesson = LESSONS.find((l) => l.id === libId);
      if (lesson) out.push(libraryExercise(lesson, d));
      continue;
    }
    out.push(buildExercise(d));
  }
  return out;
}

export const FINGER_EXERCISES: readonly FingerExercise[] = build();

/** Id bài áp dụng → bài thư viện (để test kiểm tra liên kết còn tồn tại). */
export const TECHNIQUE_LIBRARY_LINKS: Readonly<Record<string, string>> = LIBRARY_LINKS;

export function exerciseById(id: string): FingerExercise | undefined {
  return FINGER_EXERCISES.find((e) => e.id === id);
}

/** Bài kỹ thuật ứng với một bài (id bài kỹ thuật, hoặc bài thư viện được dùng làm bài áp dụng). */
export function exerciseForLesson(lessonId: string): FingerExercise | undefined {
  return FINGER_EXERCISES.find((e) => e.id === lessonId) ?? FINGER_EXERCISES.find((e) => e.libraryLessonId === lessonId);
}
